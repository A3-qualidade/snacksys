
-- SnackSys - V1
-- Estrutura inicial do banco de dados PostgreSQL

-- 1. Categorias
CREATE TABLE categorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(100) NOT NULL UNIQUE,
    ativa BOOLEAN NOT NULL DEFAULT TRUE
);

-- 2. Produtos
CREATE TABLE produtos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    categoria_id BIGINT NOT NULL REFERENCES categorias(id),
    nome VARCHAR(120) NOT NULL,
    descricao TEXT,
    preco NUMERIC(12,2) NOT NULL CHECK (preco > 0),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    controla_estoque BOOLEAN NOT NULL DEFAULT TRUE,
    estoque_minimo INTEGER NOT NULL DEFAULT 0
        CHECK (estoque_minimo >= 0)
);

-- 3. Estoques
CREATE TABLE estoques (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL UNIQUE REFERENCES produtos(id),
    quantidade INTEGER NOT NULL DEFAULT 0
        CHECK (quantidade >= 0),
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- 4. Funcionarios
CREATE TABLE funcionarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cargo VARCHAR(60) NOT NULL,
    login VARCHAR(100) NOT NULL UNIQUE,
    senha_hash VARCHAR(255) NOT NULL,
    perfil VARCHAR(20) NOT NULL
        CHECK (perfil IN ('GERENTE', 'ATENDENTE')),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

-- 5. Clientes
CREATE TABLE clientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    cpf VARCHAR(11) UNIQUE
        CHECK (cpf ~ '^[0-9]{11}$'),
    telefone VARCHAR(20)
);

-- 6. Pedidos
CREATE TABLE pedidos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id BIGINT REFERENCES clientes(id),
    chave_idempotencia UUID NOT NULL UNIQUE,
    numero_chamada INTEGER NOT NULL CHECK (numero_chamada > 0),
    data_chamada DATE NOT NULL DEFAULT CURRENT_DATE,
    nome_chamada VARCHAR(100),
    status VARCHAR(30) NOT NULL DEFAULT 'AGUARDANDO_PAGAMENTO'
        CHECK (status IN (
            'AGUARDANDO_PAGAMENTO',
            'RECEBIDO',
            'EM_PREPARO',
            'PRONTO',
            'ENTREGUE',
            'CANCELADO'
        )),
    valor_total NUMERIC(12,2) NOT NULL CHECK (valor_total >= 0),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    atualizado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (data_chamada, numero_chamada)
);

-- 7. Itens do pedido
CREATE TABLE itens_pedido (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    quantidade INTEGER NOT NULL CHECK (quantidade BETWEEN 1 AND 10),
    preco_unitario NUMERIC(12,2) NOT NULL CHECK (preco_unitario >= 0),
    subtotal NUMERIC(12,2) NOT NULL,
    CHECK (subtotal = quantidade * preco_unitario)
);

-- 8. Movimentacoes de estoque
CREATE TABLE movimentacoes_estoque (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    produto_id BIGINT NOT NULL REFERENCES produtos(id),
    pedido_id BIGINT REFERENCES pedidos(id),
    funcionario_id BIGINT REFERENCES funcionarios(id),
    tipo VARCHAR(30) NOT NULL
        CHECK (tipo IN (
            'ENTRADA',
            'SAIDA_VENDA',
            'AJUSTE',
            'ESTORNO'
        )),
    quantidade INTEGER NOT NULL,
    motivo VARCHAR(255),
    criado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CHECK (
        (tipo IN ('ENTRADA', 'ESTORNO') AND quantidade > 0)
        OR (tipo = 'SAIDA_VENDA' AND quantidade < 0)
        OR (tipo = 'AJUSTE' AND quantidade <> 0)
    ),

    CHECK (
        tipo <> 'AJUSTE'
        OR (
            motivo IS NOT NULL
            AND LENGTH(TRIM(motivo)) > 0
        )
    ),

    CHECK (
        tipo NOT IN ('SAIDA_VENDA', 'ESTORNO')
        OR pedido_id IS NOT NULL
    ),

    CHECK (
        tipo NOT IN ('ENTRADA', 'AJUSTE')
        OR funcionario_id IS NOT NULL
    )
);

-- 9. Pagamentos
CREATE TABLE pagamentos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pedido_id BIGINT NOT NULL REFERENCES pedidos(id),
    funcionario_id BIGINT NOT NULL REFERENCES funcionarios(id),
    forma VARCHAR(30) NOT NULL
        CHECK (forma IN (
            'DINHEIRO',
            'PIX',
            'CARTAO_CREDITO',
            'CARTAO_DEBITO'
        )),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDENTE'
        CHECK (status IN (
            'PENDENTE',
            'APROVADO',
            'RECUSADO'
        )),
    valor NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    registrado_em TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Indices para consultas e relacionamentos
CREATE INDEX idx_produtos_categoria
    ON produtos(categoria_id);

CREATE INDEX idx_pedidos_cliente
    ON pedidos(cliente_id);

CREATE INDEX idx_pedidos_status
    ON pedidos(status);

CREATE INDEX idx_pedidos_data
    ON pedidos(criado_em);

CREATE INDEX idx_itens_pedido
    ON itens_pedido(pedido_id);

CREATE INDEX idx_itens_produto
    ON itens_pedido(produto_id);

CREATE INDEX idx_movimentacoes_produto
    ON movimentacoes_estoque(produto_id);

CREATE INDEX idx_movimentacoes_pedido
    ON movimentacoes_estoque(pedido_id);

CREATE INDEX idx_pagamentos_pedido
    ON pagamentos(pedido_id);

-- Impede mais de um pagamento aprovado por pedido
CREATE UNIQUE INDEX idx_pagamento_aprovado_unico
    ON pagamentos(pedido_id)
    WHERE status = 'APROVADO';
